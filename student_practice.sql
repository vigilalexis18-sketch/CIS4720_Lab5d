-- STEP 7. Create the student_scores view from a LEFT OUTER JOIN,
--         then query it twice
-- =================================================================

-- Create a view that displays each student and their quiz scores.
-- Use a LEFT JOIN so students without scores are included.
CREATE VIEW student_scores AS
SELECT
    s.student_id,
    CONCAT(s.first_name, ' ', s.last_name) AS student_name,
    t.test_name,
    t.score
FROM students AS s
LEFT OUTER JOIN test_scores AS t
    ON s.student_id = t.student_id;

-- Display all students and their quiz scores.
SELECT * FROM student_scores;

-- Display only Maria Elena Jimenez's quiz results.
SELECT *
FROM student_scores
WHERE student_id = 3;

-- =================================================================
-- STEP 8. Create the calculate_gpa function
--
-- Paste the block from the handout in here so it is part of what you
-- submit, then RUN IT AT THE COMMAND PROMPT, not in VS Code.
--
-- DELIMITER is an instruction to the mysql command prompt program. It is
-- not SQL. Run it here and the server rejects it with
--   ERROR 1064 ... near 'DELIMITER $$' at line 1
-- =================================================================

CREATE FUNCTION calculate_gpa(p_student_id INT)
RETURNS DECIMAL(4,2)
DETERMINISTIC
READS SQL DATA
BEGIN
    -- Create a variable to hold the calculated average.
    DECLARE v_gpa DECIMAL(4,2);

    -- Find the student's average score and round it to two decimals.
    SELECT ROUND(AVG(score), 2)
    INTO v_gpa
    FROM test_scores
    WHERE student_id = p_student_id
      AND score IS NOT NULL;

    -- Return zero if the student has no scores.
    RETURN IFNULL(v_gpa, 0.00);
END$$

-- Return to the regular semicolon delimiter.
DELIMITER ;


